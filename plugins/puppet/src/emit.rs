//! Stage four: a manifest becomes its final files.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use meridian_sdk::{CompileError, Value};

use crate::{refuse_declaration, Attr, Declaration, Manifest, Reference};

/// Holds the class: every resource the document declares.
pub const MANIFEST_PATH: &str = "manifests/init.pp";
/// Holds the node statement that assigns the class to the host. Keeping the
/// two apart lets the class be reused by a site that classifies nodes some
/// other way.
pub const SITE_PATH: &str = "site.pp";

/// Marks the output as generated. Puppet manifests are commonly edited in
/// place, and an operator who does not know a file is compiled will lose
/// their changes on the next run without being told why.
const HEADER: &str =
    "# Generated by Meridian. Do not edit; this file is compiled from a Meridian document.\n";

/// Renders a manifest. This stage performs no mapping and no ordering.
///
/// It owns every formatting decision, including the one Puppet authors care
/// most about: the arrows in a resource body are aligned on the longest
/// attribute name of that resource, which is what the Puppet style guide asks
/// for and what keeps an edit to one resource from rewriting every other.
pub(crate) fn serialise(manifest: &Manifest) -> Result<BTreeMap<String, String>, CompileError> {
    let mut body = format!("{HEADER}\nclass {} {{\n", manifest.class);
    for (i, declaration) in manifest.resources.iter().enumerate() {
        if i > 0 {
            body.push('\n');
        }
        write_declaration(&mut body, declaration)?;
    }
    body.push_str("}\n");

    // The host is a Puppet string like any other, so a quote in it cannot
    // end the node statement. One that is not a host name at all was
    // refused by transform.
    let site = format!(
        "{HEADER}\nnode {} {{\n  include {}\n}}\n",
        quote(&manifest.host),
        manifest.class
    );
    Ok(BTreeMap::from([
        (MANIFEST_PATH.to_owned(), body),
        (SITE_PATH.to_owned(), site),
    ]))
}

/// Lays one declaration out in a fixed order: `ensure` first because it is
/// what an operator reads to know what the resource does, then the remaining
/// attributes alphabetically, then the metaparameters that place the resource
/// in the graph.
fn write_declaration(out: &mut String, d: &Declaration) -> Result<(), CompileError> {
    let mut rows: Vec<(&str, String)> = Vec::new();
    if let Some(ensure) = d.attrs.get("ensure") {
        rows.push(("ensure", attribute(ensure, d)?));
    }
    for (name, value) in &d.attrs {
        if name != "ensure" {
            rows.push((name, attribute(value, d)?));
        }
    }
    if !d.require.is_empty() {
        rows.push(("require", references(&d.require)));
    }
    if !d.notify.is_empty() {
        rows.push(("notify", references(&d.notify)));
    }

    let width = rows.iter().map(|(name, _)| name.len()).max().unwrap_or(0);
    let _ = writeln!(out, "  {} {{ '{}':", d.r#type, d.title);
    for (name, value) in rows {
        let _ = writeln!(out, "    {name:<width$} => {value},");
    }
    out.push_str("  }\n");
    Ok(())
}

/// One or more resource references. A single reference is written bare, which
/// is both what Puppet accepts and what an author would have written.
fn references(refs: &[Reference]) -> String {
    match refs {
        [one] => one.to_string(),
        many => format!(
            "[{}]",
            many.iter()
                .map(Reference::to_string)
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn attribute(attr: &Attr, d: &Declaration) -> Result<String, CompileError> {
    match attr {
        Attr::Bare(word) => Ok((*word).to_owned()),
        Attr::Value(value) => literal(value, d),
    }
}

/// Renders a param value as Puppet source. A value that cannot be represented
/// is an error and not a best-effort rendering.
fn literal(value: &Value, d: &Declaration) -> Result<String, CompileError> {
    Ok(match value {
        Value::Null => {
            return Err(refuse_declaration(
                d,
                "unrepresentable-value",
                "a null value cannot be written as Puppet source".to_owned(),
            ))
        }
        Value::String(s) => quote(s),
        // A plugin is never sent a secret as a value; one would be written as its mask.
        Value::Secret(_) => quote(meridian_sdk::SENSITIVE),
        Value::Bool(b) => b.to_string(),
        Value::Int(i) => i.to_string(),
        Value::Uint(u) => u.to_string(),
        // A float that is a whole number is written without a fractional
        // part, so an attribute like a uid means what the author wrote.
        Value::Float(f) if f.fract() == 0.0 && f.abs() < 9.0e15 => format!("{}", *f as i64),
        Value::Float(f) => f.to_string(),
        Value::List(items) => {
            let parts = items
                .iter()
                .map(|item| literal(item, d))
                .collect::<Result<Vec<_>, _>>()?;
            format!("[{}]", parts.join(", "))
        }
        Value::Map(map) => {
            let parts = map
                .iter()
                .map(|(key, item)| Ok(format!("{} => {}", quote(key), literal(item, d)?)))
                .collect::<Result<Vec<_>, CompileError>>()?;
            format!("{{ {} }}", parts.join(", "))
        }
    })
}

/// Renders a string as a Puppet string literal.
///
/// Single quotes are preferred because Puppet does not interpolate inside
/// them, so a value holding a dollar sign stays the value the author wrote.
/// A string a single-quoted literal cannot hold falls back to double quotes,
/// where interpolation is escaped explicitly.
pub(crate) fn quote(s: &str) -> String {
    if !s.contains(['\'', '\\', '\n', '\r', '\t']) {
        return format!("'{s}'");
    }
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
