//! Stage four: a cookbook becomes its files.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use meridian_sdk::{SecretName, Value};

use crate::{Block, Cookbook};

/// Where a cookbook's metadata is written.
pub fn metadata_path(cookbook: &str) -> String {
    format!("cookbooks/{cookbook}/metadata.rb")
}

/// Where a cookbook's default recipe is written: every resource the document
/// declares.
pub fn recipe_path(cookbook: &str) -> String {
    format!("cookbooks/{cookbook}/recipes/default.rb")
}

/// Marks the output as generated. Cookbooks are commonly edited in place, and
/// an operator who does not know a file is compiled will lose their changes
/// on the next run without being told why.
const HEADER: &str =
    "# Generated by Meridian. Do not edit; this file is compiled from a Meridian document.\n";

/// Renders a cookbook. This stage performs no mapping and no ordering.
///
/// A block is laid out the way Chef's own documentation lays one out:
/// properties, then guards, then notifications, then the action.
pub(crate) fn serialise(cookbook: &Cookbook) -> BTreeMap<String, String> {
    let mut recipe = HEADER.to_owned();
    for block in &cookbook.blocks {
        recipe.push('\n');
        write_block(&mut recipe, block, &cookbook.secrets);
    }

    let metadata = format!(
        "{HEADER}\nname {}\nversion '0.1.0'\ndescription {}\n",
        quote(&cookbook.name),
        quote(&format!(
            "Compiled by Meridian from the document {}.",
            cookbook.document
        )),
    );
    BTreeMap::from([
        (metadata_path(&cookbook.name), metadata),
        (recipe_path(&cookbook.name), recipe),
    ])
}

fn write_block(out: &mut String, block: &Block, secrets: &[SecretName]) {
    let _ = writeln!(out, "{} {} do", block.resource, quote(&block.name));
    for (name, value) in &block.properties {
        let _ = writeln!(out, "  {name} {}", literal(value, secrets));
    }
    // A resource handed a secret is not allowed to show it: `sensitive`
    // keeps its diff and its properties out of what chef-client prints.
    if block.properties.values().any(holds_secret) {
        out.push_str("  sensitive true\n");
    }
    if !block.only_if.is_empty() {
        let _ = writeln!(out, "  only_if {{ {} }}", block.only_if.trim());
    }
    for notify in &block.notifies {
        let _ = writeln!(
            out,
            "  notifies :{}, {}, :delayed",
            notify.action,
            quote(&notify.target)
        );
    }
    match block.actions.as_slice() {
        [one] => {
            let _ = writeln!(out, "  action :{one}");
        }
        several => {
            let list: Vec<String> = several.iter().map(|a| format!(":{a}")).collect();
            let _ = writeln!(out, "  action [{}]", list.join(", "));
        }
    }
    out.push_str("end\n");
}

/// Whether a value refers to a secret anywhere inside it.
fn holds_secret(value: &Value) -> bool {
    match value {
        Value::Secret(_) => true,
        Value::List(items) => items.iter().any(holds_secret),
        Value::Map(map) => map.values().any(holds_secret),
        _ => false,
    }
}

/// A value as a Ruby literal.
fn literal(value: &Value, secrets: &[SecretName]) -> String {
    match value {
        Value::Null => "nil".to_owned(),
        Value::Bool(b) => b.to_string(),
        Value::Int(i) => i.to_string(),
        Value::Uint(u) => u.to_string(),
        Value::Float(f) => {
            let text = f.to_string();
            if text.contains(['.', 'e', 'E']) {
                text
            } else {
                format!("{text}.0")
            }
        }
        Value::String(s) => quote(s),
        // A secret is read from the node's attributes when the recipe runs;
        // one the graph does not name is written as its mask.
        Value::Secret(at) => secrets
            .iter()
            .find(|s| s.secret == *at)
            .map(|s| crate::secret_reference(&s.name))
            .unwrap_or_else(|| quote(meridian_sdk::SENSITIVE)),
        Value::List(items) => {
            let items: Vec<String> = items.iter().map(|v| literal(v, secrets)).collect();
            format!("[{}]", items.join(", "))
        }
        Value::Map(map) => {
            if map.is_empty() {
                return "{}".to_owned();
            }
            let pairs: Vec<String> = map
                .iter()
                .map(|(k, v)| format!("{} => {}", quote(k), literal(v, secrets)))
                .collect();
            format!("{{ {} }}", pairs.join(", "))
        }
    }
}

/// A Ruby string. Single quotes when the text can be read as it stands,
/// because nothing inside them is interpreted; double quotes with escapes
/// when it holds a line break or another control character.
pub(crate) fn quote(s: &str) -> String {
    if !s.chars().any(char::is_control) {
        return format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"));
    }
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            // `#{`, `#$` and `#@` interpolate inside double quotes.
            '#' => out.push_str("\\#"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_string_is_quoted_so_ruby_reads_it_back_unchanged() {
        assert_eq!(quote("nginx"), "'nginx'");
        assert_eq!(quote("it's"), "'it\\'s'");
        assert_eq!(quote("a\\b"), "'a\\\\b'");
        assert_eq!(quote("#{x} $y"), "'#{x} $y'");
        assert_eq!(quote("a\nb"), "\"a\\nb\"");
        assert_eq!(quote("#{x}\n\"q\""), "\"\\#{x}\\n\\\"q\\\"\"");
    }

    #[test]
    fn values_are_ruby_literals() {
        assert_eq!(literal(&Value::Int(1200), &[]), "1200");
        assert_eq!(literal(&Value::Bool(true), &[]), "true");
        assert_eq!(
            literal(
                &Value::List(vec![
                    Value::String("deploy".into()),
                    Value::String("sudo".into())
                ]),
                &[]
            ),
            "['deploy', 'sudo']"
        );
    }
}
