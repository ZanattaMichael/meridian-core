//! Exports the document language as a JSON Schema, for editors that
//! validate YAML against one.
//!
//! The schema is generated from the tables the parser reads
//! ([`meridian_ir::schema`]) and from what the loaded plugins declare, so it
//! is never written by hand and cannot fall behind the compiler. It says
//! less than the compiler does: a schema cannot check that a `dependsOn`
//! names a real resource. For that, use the language server.

use meridian_ir::schema::{self, Field, Role, Shape, Type};
use serde_json::{json, Map, Value};

use crate::catalog::{pattern_parts, Catalog, PatternPart, Target};

/// The dialect the export is written in. Draft 7 is the one every YAML
/// editor integration understands.
pub const DIALECT: &str = "http://json-schema.org/draft-07/schema#";

/// Builds the schema. With `only`, target-specific rules are written for
/// that one target; otherwise for every target in the catalog.
pub fn export(catalog: &Catalog, only: Option<&str>) -> Value {
    let targets: Vec<&Target> = catalog
        .targets()
        .filter(|t| only.is_none_or(|name| t.name == name))
        .collect();

    let mut definitions = Map::new();
    let mut seen = Vec::new();
    for (_, shape) in schema::DOCUMENTS {
        define(shape, &targets, &mut definitions, &mut seen);
    }
    for target in &targets {
        if target.knows_types() {
            definitions.insert(resource_definition(&target.name), resource_for(target));
        }
    }

    // A document is checked against the shape its `kind` names. Until a kind
    // is typed, only the header fields are known.
    let by_kind: Vec<Value> = schema::DOCUMENTS
        .iter()
        .map(|(kind, shape)| {
            json!({
                "if": {
                    "properties": { "kind": { "const": kind.as_str() } },
                    "required": ["kind"]
                },
                "then": { "$ref": reference(shape.name) }
            })
        })
        .collect();
    let header = &schema::DOCUMENTS[0].1;
    let mut properties = Map::new();
    for name in ["apiVersion", "kind"] {
        if let Some(field) = header.field(name) {
            properties.insert(name.to_owned(), field_schema(field, &targets));
        }
    }

    json!({
        "$schema": DIALECT,
        "$id": "https://raw.githubusercontent.com/ZanattaMichael/meridian-core/main/schemas/meridian-v1.schema.json",
        "title": "Meridian document",
        "description": "A Meridian document: an Infrastructure or a ResourceSet. Generated by `meridian schema`; do not edit.",
        "type": "object",
        "required": ["apiVersion", "kind"],
        "properties": properties,
        "allOf": by_kind,
        "definitions": definitions,
    })
}

fn reference(name: &str) -> String {
    format!("#/definitions/{name}")
}

fn resource_definition(target: &str) -> String {
    format!("Resource.{target}")
}

fn define(
    shape: &'static Shape,
    targets: &[&Target],
    definitions: &mut Map<String, Value>,
    seen: &mut Vec<&'static str>,
) {
    if seen.contains(&shape.name) {
        return;
    }
    seen.push(shape.name);
    let mut properties = Map::new();
    let mut required = Vec::new();
    for field in shape.fields {
        properties.insert(field.name.to_owned(), field_schema(field, targets));
        if field.required {
            required.push(Value::from(field.name));
        }
        if let Type::Object(next) | Type::List(next) = &field.ty {
            define(next, targets, definitions, seen);
        }
    }
    let mut definition = Map::new();
    definition.insert("description".into(), shape.doc.into());
    definition.insert("type".into(), "object".into());
    definition.insert("additionalProperties".into(), false.into());
    if !required.is_empty() {
        definition.insert("required".into(), required.into());
    }
    definition.insert("properties".into(), properties.into());

    // A spec's resources follow the rules of the target the spec names.
    let per_target: Vec<Value> =
        if shape.field("target").is_some() && shape.field("resources").is_some() {
            targets
                .iter()
                .filter(|t| t.knows_types())
                .map(|t| {
                    json!({
                        "if": {
                            "properties": { "target": { "const": t.name } },
                            "required": ["target"]
                        },
                        "then": {
                            "properties": {
                                "resources": {
                                    "items": { "$ref": reference(&resource_definition(&t.name)) }
                                }
                            }
                        }
                    })
                })
                .collect()
        } else {
            Vec::new()
        };
    if !per_target.is_empty() {
        definition.insert("allOf".into(), per_target.into());
    }
    definitions.insert(shape.name.to_owned(), definition.into());
}

/// A YAML scalar that the compiler reads as text: `targetVersion: 3` is the
/// string "3", so a number must not be flagged.
fn scalar_as_text() -> Value {
    json!(["string", "number", "boolean"])
}

fn field_schema(field: &Field, targets: &[&Target]) -> Value {
    let mut out = Map::new();
    out.insert("description".into(), field.doc.into());
    match &field.ty {
        Type::String => {
            match field.role {
                Role::Target if !targets.is_empty() => {
                    out.insert("type".into(), "string".into());
                    let one_of: Vec<Value> = targets
                        .iter()
                        .map(|t| {
                            json!({
                                "const": t.name,
                                "description": format!("{} ({})", t.name, t.category),
                            })
                        })
                        .collect();
                    out.insert("oneOf".into(), one_of.into());
                }
                Role::TargetVersion | Role::ResourceState => {
                    out.insert("type".into(), scalar_as_text());
                }
                _ => {
                    out.insert("type".into(), "string".into());
                }
            }
            if field.required {
                out.insert("minLength".into(), 1.into());
            }
        }
        Type::Enum(choices) => {
            out.insert("type".into(), "string".into());
            let one_of: Vec<Value> = choices
                .iter()
                .map(|c| json!({ "const": c.value, "description": c.doc }))
                .collect();
            out.insert("oneOf".into(), one_of.into());
        }
        Type::Object(shape) => {
            out.insert("$ref".into(), reference(shape.name).into());
        }
        Type::List(shape) => {
            out.insert("type".into(), "array".into());
            out.insert("items".into(), json!({ "$ref": reference(shape.name) }));
            if field.required {
                out.insert("minItems".into(), 1.into());
            }
        }
        Type::Bool => {
            out.insert("type".into(), "boolean".into());
        }
        Type::StringList => {
            out.insert("type".into(), "array".into());
            out.insert("items".into(), json!({ "type": scalar_as_text() }));
        }
        Type::StringMap => {
            out.insert("type".into(), "object".into());
            out.insert(
                "additionalProperties".into(),
                json!({ "type": scalar_as_text() }),
            );
        }
        Type::Params => {
            out.insert("type".into(), "object".into());
        }
    }
    // JSON Schema ignores keywords beside `$ref` in draft 7, so a described
    // reference is wrapped.
    if out.contains_key("$ref") {
        let target = out.remove("$ref").unwrap_or_default();
        return json!({
            "description": field.doc,
            "allOf": [{ "$ref": target }],
        });
    }
    out.into()
}

/// A regular expression for a type pattern such as `<provider>_<type>`.
fn pattern_regex(pattern: &str) -> String {
    let mut out = String::from("^");
    for part in pattern_parts(pattern) {
        match part {
            PatternPart::Placeholder(_) => out.push_str(".+"),
            PatternPart::Literal(text) => {
                for c in text.chars() {
                    if !c.is_ascii_alphanumeric() && c != '_' {
                        out.push('\\');
                    }
                    out.push(c);
                }
            }
        }
    }
    out.push('$');
    out
}

fn param_schema(param: &meridian_sdk::ParamSchema) -> Value {
    use meridian_sdk::ParamKind;
    let mut out = Map::new();
    if !param.description.is_empty() {
        out.insert("description".into(), param.description.clone().into());
    }
    // A param may always hold a `${...}` reference, which is a string
    // whatever the param's own kind is.
    let kind = match param.kind {
        ParamKind::Any => None,
        ParamKind::String => Some(scalar_as_text()),
        ParamKind::Bool => Some(json!(["boolean", "string"])),
        ParamKind::Integer => Some(json!(["integer", "string"])),
        ParamKind::Number => Some(json!(["number", "string"])),
        ParamKind::List => Some(json!(["array", "string"])),
        ParamKind::Map => Some(json!(["object", "string"])),
    };
    if let Some(kind) = kind {
        out.insert("type".into(), kind);
    }
    if !param.values.is_empty() {
        out.insert("enum".into(), param.values.clone().into());
    }
    out.into()
}

/// The rules one target adds to a resource: which types exist, and for each
/// described type its states and params.
fn resource_for(target: &Target) -> Value {
    let literal: Vec<&str> = target
        .types
        .iter()
        .filter(|t| !t.is_pattern())
        .map(|t| t.r#type.as_str())
        .collect();
    let mut any_of = Vec::new();
    if !literal.is_empty() {
        any_of.push(json!({ "enum": literal }));
    }
    for t in target.types.iter().filter(|t| t.is_pattern()) {
        any_of.push(json!({ "pattern": pattern_regex(&t.r#type) }));
    }

    let mut all_of = vec![
        json!({ "$ref": reference(schema::RESOURCE.name) }),
        json!({ "properties": { "type": { "anyOf": any_of } } }),
    ];
    for t in target.types.iter().filter(|t| !t.is_pattern()) {
        let mut then = Map::new();
        let mut properties = Map::new();
        if !t.description.is_empty() {
            then.insert("description".into(), t.description.clone().into());
        }
        if !t.open || !t.params.is_empty() {
            let mut params = Map::new();
            let mut props = Map::new();
            for param in &t.params {
                props.insert(param.name.clone(), param_schema(param));
            }
            params.insert("properties".into(), props.into());
            if !t.open {
                params.insert("additionalProperties".into(), false.into());
            }
            properties.insert("params".into(), params.into());
        }
        if !t.open {
            if t.states.is_empty() {
                // The type takes no state, so writing one is a mistake.
                properties.insert("state".into(), json!(false));
            } else {
                properties.insert("state".into(), json!({ "enum": t.states }));
            }
        }
        let required: Vec<&str> = t
            .params
            .iter()
            .filter(|p| p.required)
            .map(|p| p.name.as_str())
            .collect();
        if !required.is_empty() {
            then.insert("required".into(), json!(["params"]));
            if let Some(Value::Object(params)) = properties.get_mut("params") {
                params.insert("required".into(), required.into());
            }
        }
        if properties.is_empty() {
            continue;
        }
        then.insert("properties".into(), properties.into());
        all_of.push(json!({
            "if": {
                "properties": { "type": { "const": t.r#type } },
                "required": ["type"]
            },
            "then": then,
        }));
    }
    json!({
        "description": format!("A resource of the {} target.", target.name),
        "allOf": all_of,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_language_alone_exports_every_shape() {
        let schema = export(&Catalog::empty(), None);
        let definitions = schema["definitions"].as_object().unwrap();
        for name in [
            "Infrastructure",
            "ResourceSet",
            "Metadata",
            "Resource",
            "Dependency",
            "Notification",
            "Output",
            "TargetHost",
        ] {
            assert!(definitions.contains_key(name), "missing {name}");
        }
        let resource = &definitions["Resource"];
        assert_eq!(resource["additionalProperties"], false);
        assert_eq!(resource["required"], json!(["id", "type"]));
        // The order the formatter writes fields in is the order they are
        // listed in.
        let fields: Vec<&String> = resource["properties"].as_object().unwrap().keys().collect();
        assert_eq!(fields[..3], ["id", "type", "state"]);
        assert_eq!(schema["allOf"].as_array().unwrap().len(), 2);
    }

    #[test]
    fn a_pattern_becomes_an_anchored_expression() {
        assert_eq!(pattern_regex("<provider>_<type>"), "^.+_.+$");
        assert_eq!(pattern_regex("data.<type>"), "^data\\..+$");
        assert_eq!(
            pattern_regex("<Namespace>/<type>@<api-version>"),
            "^.+\\/.+\\@.+$"
        );
    }
}
